def link(n): return "[[%s]]" % n
def lst(xs): return ", ".join(link(x) for x in sorted(set(xs)))
MARK = "<!-- ручное -->"

def write(path, text):
    old = ""
    if os.path.exists(path):
        old = open(path, encoding="utf-8").read()
    tail = ""
    if MARK in old:
        tail = old.split(MARK, 1)[1]
    with open(path, "w", encoding="utf-8") as f:
        f.write(text.rstrip("\n") + "\n\n" + MARK + (tail if tail else "\n"))

